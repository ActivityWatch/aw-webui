import { createLocalVue, mount, shallowMount } from '@vue/test-utils';
import BootstrapVue from 'bootstrap-vue';
import VueI18n from 'vue-i18n';
import { createPinia, PiniaVuePlugin, setActivePinia } from 'pinia';
import LanguageSettings from '~/views/settings/LanguageSettings.vue';
import { useSettingsStore } from '~/stores/settings';
import { LANGUAGE_NAMES, SUPPORTED, i18n, setAppLocale } from '~/i18n';

const localVue = createLocalVue();
localVue.use(PiniaVuePlugin);
localVue.use(BootstrapVue);
// Install the real instance-bound $t on localVue, above the global English-only stub.
localVue.use(VueI18n);

describe('LanguageSettings', () => {
  beforeEach(() => {
    setActivePinia(createPinia());
    setAppLocale('en');
  });

  afterEach(() => setAppLocale('en'));

  test('offers every supported locale, in order, by its endonym', () => {
    useSettingsStore().$patch({ _loaded: true });
    const wrapper = shallowMount(LanguageSettings as any, {
      stubs: { 'b-select': { template: '<select><slot /></select>' } },
      mocks: { $t: (key: string) => key },
    });

    const options = wrapper.findAll('option').wrappers;
    expect(options.map(o => o.attributes('value'))).toEqual(SUPPORTED);
    expect(options.map(o => o.text())).toEqual(SUPPORTED.map(code => LANGUAGE_NAMES[code]));
    wrapper.destroy();
  });

  test('shows English fallback guidance for non-English locales and hides it when switching back', async () => {
    const store = useSettingsStore();
    store._loaded = true;
    store.locale = 'en';
    // Keep the real reactive update, without persisting to a live server.
    jest.spyOn(store, 'update').mockImplementation(async values => {
      store.$patch(values);
    });
    const wrapper = mount(LanguageSettings, { localVue, i18n });

    expect(wrapper.find('[data-testid="translation-quality-note"]').exists()).toBe(false);
    for (const locale of ['fr', 'ar', 'sv']) {
      await wrapper.find('select').setValue(locale);
      expect(wrapper.find('h5').text()).toBe(i18n.t('settings.language.title'));
      expect(wrapper.find('h5').text()).not.toBe('Language');
      const note = wrapper.find('[data-testid="translation-quality-note"]');
      expect(note.exists()).toBe(true);
      expect(note.text()).toContain(
        'Some translations were generated by AI and may contain errors.'
      );
      expect(note.find('a').text()).toBe('Native-speaker contributions are welcome.');
      expect(note.find('a').attributes('href')).toBe(
        'https://github.com/ActivityWatch/aw-webui/issues'
      );
      expect(store.locale).toBe(locale);
      expect(i18n.locale).toBe(locale);
    }
    await wrapper.find('select').setValue('en');
    expect(wrapper.find('[data-testid="translation-quality-note"]').exists()).toBe(false);
    wrapper.destroy();
  });
});
